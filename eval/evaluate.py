"""ReliefRank evaluation. Run with Ctrl+F5 (no arguments).

1. Extraction accuracy: runs the real extractor on packs/<lang>/tests.json and
   compares each field with the expected value.
2. Top-10 critical hit rate: extracts + scores every message in
   data/demo_messages.json, ranks them, and counts how many messages labelled
   critical land in the top 10.

Results are printed and written to eval/results.md. Nothing is estimated:
if the extractor or scorer cannot be imported, the script stops with an error.
Owner: Radhakrishnan
"""
import importlib
import inspect
import json
import os
import re
import sys
import time

# ---- Settings (edit here, no command-line arguments) -----------------------
PACK = "en"
TOP_N = 10
# "module:function". Change these if the function names in the repo differ.
EXTRACT_FN = "reliefrank.extract:extract"   # text -> dict of case fields
SCORE_FN = "reliefrank.score:score"         # case dict -> number, or (number, reasons), or dict with "score"
FIELDS = ["people_count", "vulnerable", "trapped", "location_text", "phone"]
WRITE_RESULTS = True
# -----------------------------------------------------------------------------

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)


def load_fn(spec):
    mod_name, fn_name = spec.split(":")
    return getattr(importlib.import_module(mod_name), fn_name)


def call_extract(fn, text):
    """Pass the pack too if the extractor accepts a second argument."""
    params = inspect.signature(fn).parameters
    out = fn(text, PACK) if len(params) >= 2 else fn(text)
    if hasattr(out, "model_dump"):      # pydantic v2
        out = out.model_dump()
    elif hasattr(out, "dict"):          # pydantic v1
        out = out.dict()
    return out or {}


def to_score(out):
    if isinstance(out, (int, float)):
        return float(out)
    if isinstance(out, (tuple, list)):
        return float(out[0])
    if isinstance(out, dict):
        return float(out.get("score", 0))
    return float(getattr(out, "score", 0))


def digits(x):
    return re.sub(r"\D", "", str(x or ""))[-10:]


def field_match(field, expected, got):
    if field == "phone":
        return digits(expected) == digits(got)
    if field == "location_text":
        if not expected:
            return not got
        return bool(got) and expected.lower() in str(got).lower()
    if field == "people_count":
        try:
            return (expected is None and got in (None, 0, "")) or int(got) == int(expected)
        except (TypeError, ValueError):
            return False
    if isinstance(expected, bool):
        return bool(got) == expected
    return expected == got


def main():
    extract = load_fn(EXTRACT_FN)
    score = load_fn(SCORE_FN)

    with open(os.path.join(ROOT, "packs", PACK, "tests.json"), encoding="utf-8") as f:
        tests = json.load(f)["tests"]
    with open(os.path.join(ROOT, "data", "demo_messages.json"), encoding="utf-8") as f:
        demo = json.load(f)["messages"]

    # 1. Extraction accuracy
    correct = {f: 0 for f in FIELDS}
    failures = []
    extracted = {}
    t0 = time.time()
    for t in tests:
        try:
            got = call_extract(extract, t["text"])
        except Exception as e:  # count a crash as wrong on every field
            got = {}
            failures.append(f"{t['id']}: extractor error: {e}")
        extracted[t["id"]] = got
        for f in FIELDS:
            if field_match(f, t["expected"].get(f), got.get(f)):
                correct[f] += 1
            else:
                failures.append(f"{t['id']} {f}: expected {t['expected'].get(f)!r}, got {got.get(f)!r}")
    secs = (time.time() - t0) / max(len(tests), 1)

    # 2. Top-N critical hit rate (reuses extractions where ids match)
    ranked = []
    for m in demo:
        case = extracted.get(m["id"])
        if case is None:
            case = call_extract(extract, m["text"])
        try:
            s = to_score(score(case))
        except Exception as e:
            failures.append(f"{m['id']}: scorer error: {e}")
            s = 0.0
        ranked.append((s, m["id"], m["critical"]))
    ranked.sort(key=lambda r: -r[0])
    top = ranked[:TOP_N]
    n_critical = sum(1 for m in demo if m["critical"])
    hits = sum(1 for r in top if r[2])
    possible = min(TOP_N, n_critical)

    # Report
    lines = ["# ReliefRank evaluation results", "",
             f"Generated by `eval/evaluate.py` on {time.strftime('%Y-%m-%d %H:%M')} "
             f"using `{EXTRACT_FN}` and `{SCORE_FN}`. Test data is synthetic (written by the team).", "",
             "## Extraction accuracy", "",
             f"{len(tests)} test messages, average {secs:.1f} s per message.", "",
             "| Field | Correct | Accuracy |", "| --- | --- | --- |"]
    for f in FIELDS:
        lines.append(f"| {f} | {correct[f]}/{len(tests)} | {100 * correct[f] / len(tests):.0f}% |")
    overall = sum(correct.values()) / (len(FIELDS) * len(tests))
    lines += [f"| **all fields** | | **{100 * overall:.0f}%** |", "",
              f"## Top-{TOP_N} critical hit rate", "",
              f"{hits} of the top {TOP_N} ranked messages are labelled critical "
              f"({hits}/{possible} possible; {n_critical} critical messages in {len(demo)}).", "",
              "Ranking here is per message, before duplicate merging.", "",
              "| Rank | Message | Score | Critical |", "| --- | --- | --- | --- |"]
    for i, (s, mid, crit) in enumerate(top, 1):
        lines.append(f"| {i} | {mid} | {s:g} | {'yes' if crit else 'no'} |")
    if failures:
        lines += ["", "## Mismatches", ""] + [f"- {x}" for x in failures]
    report = "\n".join(lines) + "\n"

    print(report)
    if WRITE_RESULTS:
        with open(os.path.join(ROOT, "eval", "results.md"), "w", encoding="utf-8") as f:
            f.write(report)
        print("Saved eval/results.md")


if __name__ == "__main__":
    main()
